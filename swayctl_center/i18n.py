LANGS = {"vi": VI}


def language() -> str:
    for var in ("SWAYCTL_LANG", "LANGUAGE", "LC_ALL", "LC_MESSAGES", "LANG"):
        value = os.environ.get(var, "")
        if value:
            # LANGUAGE may be a list (vi:en); C/POSIX means English
            return value.split(":")[0].split("_")[0].split(".")[0].lower()
    return "en"


_table = LANGS.get(language(), {})


def _(text: str) -> str:
    return _table.get(text, text)
